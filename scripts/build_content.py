#!/usr/bin/env python3
"""Bundle the bilingual lessons in content/lessons/<skill-id>.<fa|en>.md into assets/curriculum/lessons.js.

The app is offline-first and must also work from file://, so lessons are shipped as one script
(window.LESSONS = {id: {fa: markdown, en: markdown}}) instead of being fetched at runtime.
Run after editing any lesson:  python3 scripts/build_content.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "content" / "lessons"
OUT = ROOT / "assets" / "curriculum" / "lessons.js"
NAME = re.compile(r"^([a-z]+-[a-z0-9-]+)\.(fa|en)\.md$")


def main() -> int:
    lessons: dict[str, dict[str, str]] = {}
    for f in sorted(SRC.glob("*.md")):
        m = NAME.match(f.name)
        if not m:
            print(f"skipping unexpected file name: {f.name}", file=sys.stderr)
            continue
        lessons.setdefault(m.group(1), {})[m.group(2)] = f.read_text(encoding="utf-8").strip() + "\n"
    body = json.dumps(lessons, ensure_ascii=False, indent=0, sort_keys=True)
    OUT.write_text(
        "/* Generated by scripts/build_content.py from content/lessons/*.md — do not edit by hand. */\n"
        f"(typeof window !== \"undefined\" ? window : globalThis).LESSONS = {body};\n",
        encoding="utf-8",
    )
    langs = sum(len(v) for v in lessons.values())
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lessons)} skills, {langs} lesson files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
